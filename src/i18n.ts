const dict: Record<Lang, Record<Key, string>> = { en, pt }
const STORAGE_KEY = 'vini-lang'

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'pt') return saved
  } catch {
    // Armazenamento bloqueado: segue com o idioma do navegador.
  }
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

export function t(lang: Lang, key: Key): string {
  return dict[lang][key]
}

export function applyLang(lang: Lang): void {
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en'
  document.title = t(lang, 'meta.title')
  document.querySelector('meta[name="description"]')?.setAttribute('content', t(lang, 'meta.description'))
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n as Key)
  })
  document.querySelectorAll<HTMLElement>('[data-i18n-label]').forEach((el) => {
    el.setAttribute('aria-label', t(lang, el.dataset.i18nLabel as Key))
  })
  document.querySelectorAll<HTMLButtonElement>('[data-lang]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang))
  })
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    // Sem armazenamento: o idioma vale só nesta visita.
  }
}
